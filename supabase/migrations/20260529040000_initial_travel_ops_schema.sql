  expires_at timestamptz not null,
  used boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.fleet (
  id text primary key,
  model text not null,
  plate text not null,
  type text,
  status public.fleet_status_enum not null default 'Available',
  "lastService" date,
  photo text,
  age integer not null default 0,
  fuel_status integer not null default 100,
  next_service date,
  condition public.fleet_condition_enum not null default 'Good',
  notes text,
  insurance_provider text,
  insurance_policy text,
  insurance_start date,
  insurance_expiry date,
  insurance_status public.insurance_status_enum not null default 'Unknown',
  insurance_doc text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint fleet_plate_key unique (plate),
  constraint fleet_age_check check (age >= 0),
  constraint fleet_fuel_status_check check (fuel_status between 0 and 100),
  constraint fleet_service_window_check check (
    insurance_start is null or insurance_expiry is null or insurance_expiry >= insurance_start
  )
);

