create or replace function public.set_row_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.generate_enquiry_reference_id()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  reference_prefix text;
  reference_year integer;
  next_sequence integer;
begin
  if new.reference_id is not null and btrim(new.reference_id) <> '' then
    return new;
  end if;

  reference_prefix := case new.enquiry_type
    when 'cab' then 'CAB'
    when 'room' then 'ROOM'
    when 'tour' then 'TOUR'
    when 'custom' then 'CUSTOM'
    else 'GEN'
  end;

  reference_year := extract(year from coalesce(new.submitted_at, now()))::integer;

  insert into public.enquiry_counters (enquiry_type, enquiry_year, last_number)
  values (new.enquiry_type, reference_year, 1)
  on conflict (enquiry_type, enquiry_year)
  do update set last_number = public.enquiry_counters.last_number + 1
  returning last_number into next_sequence;

  new.reference_id := reference_prefix || '-' || reference_year || '-' || lpad(next_sequence::text, 4, '0');
  return new;
end;
$$;

